// TKTS Live: which shows are on the TKTS booth boards today (tdf.org/…/tkts-live/).
// TDF renders the boards in the page's HTML: one list per booth (Times Square, Lincoln Center)
// and type (Broadway, Off-Broadway), with "Updated: <date time>" and links to TDF show pages.
// When a booth is closed the page still shows the last board, so we keep each board's update
// time and the site only treats a listing as "today" if the board was updated today.
import { readFileSync, writeFileSync } from "node:fs";

const URL_ = "https://www.tdf.org/discount-ticket-programs/tkts-by-tdf/tkts-live/";
const OUT = "data/tkts.js";
const decode = (s) => s.replace(/&#0?38;|&amp;/g, "&").replace(/&#8217;|&rsquo;/g, "'").replace(/&#8211;/g, "–").replace(/&#(\d+);/g, (_, n) => String.fromCharCode(+n)).replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();

export function parse(html) {
  const boards = [];
  const panels = html.split(/<div class="tab-panel"[^>]*id="tkts-tab-/).slice(1);
  for (const p of panels) {
    const booth = p.slice(0, p.indexOf('"'));
    const status = /tkts__notice--closed/.test(p.slice(0, 4000)) ? "closed" : "open";
    for (const b of p.split(/<div class="tkts__board tkts__board--/).slice(1)) {
      const kind = b.slice(0, b.indexOf('"'));
      const upd = (decode((b.match(/tkts__updated">([\s\S]*?)<\/div>/) || [])[1] || "").match(/Updated:\s*(.+)$/) || [])[1];
      // "tomorrow-…" boards list tomorrow's matinees, sold today.
      // Open board: a grid with % off, price range and curtain time per show.
      const grid = [...b.matchAll(/<li class="tkts__grid-list-item">([\s\S]*?)<\/li>/g)].map((m) => {
        const a = m[1].match(/<a href="([^"]+)"[^>]*>([\s\S]*?)<\/a>/) || [null, null, (m[1].match(/__title">([\s\S]*?)<\/div>/) || [])[1]];
        const cell = (k) => decode((m[1].match(new RegExp(`__${k}">([\\s\\S]*?)<\\/div>`)) || [])[1] || "");
        const price = cell("discount").match(/\$?(\d+(?:\.\d+)?)(?:\s*[-–]\s*\$?(\d+(?:\.\d+)?))?/);
        const id = a[1] && (a[1].match(/\/shows\/(\d+)\//) || a[1].match(/\/shows\/(\d+)/) || [])[1];
        return a[2] ? { title: decode(a[2]), url: a[1] || null, tdfId: id || null, pct: parseInt(cell("percent")) || null,
          lo: price ? +price[1] : null, hi: price && price[2] ? +price[2] : price ? +price[1] : null, time: cell("time") || null } : null;
      }).filter(Boolean);
      const shows = grid.length ? grid : [...b.matchAll(/<li class="tkts__shows-item">([\s\S]*?)<\/li>/g)].map((m) => {
        const a = m[1].match(/<a href="([^"]+)"[^>]*>([\s\S]*?)<\/a>/);
        const extra = decode(m[1].replace(/<a[\s\S]*?<\/a>/, ""));        // price / discount text, if the board shows any
        const id = a && (a[1].match(/\/shows\/(\d+)\//) || [])[1];
        return a ? { title: decode(a[2]), url: a[1], tdfId: id || null, note: extra || null } : null;
      }).filter(Boolean);
      boards.push({ booth, kind, status, updated: upd ? upd.trim() : null, shows });
    }
  }
  return boards;
}

// "Sunday, 15 November 2026 08:18 PM" → "2026-11-15"
const dayOf = (s) => { const m = s && s.match(/(\d{1,2}) (\w+) (\d{4})/); if (!m) return null;
  const mo = ["january","february","march","april","may","june","july","august","september","october","november","december"].indexOf(m[2].toLowerCase()) + 1;
  return mo ? `${m[3]}-${String(mo).padStart(2, "0")}-${String(m[1]).padStart(2, "0")}` : null; };

async function run() {
  const res = await fetch(URL_, { headers: { "user-agent": "TheaterMaxBot/1.0 (+https://github.com/naomi-meininger/theatermax)" } });
  if (!res.ok) throw new Error("HTTP " + res.status);
  const html = await res.text();
  const boards = parse(html).map((b) => ({ ...b, day: dayOf(b.updated) }));
  // An open board with no shows parsed means the open-board markup differs: keep a copy to fix the parser.
  if (boards.some((b) => b.status === "open" && !b.shows.length)) {
    const a = html.indexOf("tkts-tabbed-booths");
    writeFileSync("data/tkts-debug.html", html.slice(a, a + 150000).replace(/<svg[\s\S]*?<\/svg>/g, ""));
  }
  if (!boards.length) throw new Error("no boards found — page layout may have changed");
  const data = { status: "ok", source: URL_, checkedAt: new Date().toISOString(), boards };
  writeFileSync(OUT, `// Auto-generated by scripts/update-tkts.mjs from TDF's TKTS Live page. Do not edit by hand.\nwindow.TM_TKTS = ${JSON.stringify(data, null, 1)};\n`);
  console.log(boards.map((b) => `${b.booth}/${b.kind} ${b.status} ${b.updated}: ${b.shows.length}`).join("\n"));
}
const args = process.argv.slice(2);
if (args[0] === "--file") console.log(JSON.stringify(parse(readFileSync(args[1], "utf8")), null, 1));
else run().catch((e) => { console.error(e.message); process.exit(1); });
