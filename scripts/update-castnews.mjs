// Cast change headlines from Playbill's public news RSS feed (playbill.com/article/playbill-rss-feeds).
// The feed only carries the latest ~10 stories, so this runs every few hours and keeps what it has
// seen for 90 days. We store only the headline, date, and link (never article text), matched to
// shows on TheaterMax, and classify each one as someone joining or someone leaving.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import vm from "node:vm";

const OUT = "data/castnews.js";
const FEEDS = [{ source: "Playbill", url: "https://playbill.com/rss/news" }];
const UA = "TheaterMax/1.0 (+https://naomi-meininger.github.io/theatermax/)";
const KEEP_DAYS = 90;

const load = (file, name) => { if (!existsSync(file)) return null; const ctx = { window: {} }; vm.runInNewContext(readFileSync(file, "utf8"), ctx); return ctx.window[name]; };
const prev = load(OUT, "TM_CASTNEWS") || { items: [] };
const live = load("data/live-shows.js", "TM_LIVE") || { shows: [] };
const extra = load("data/extra-shows.js", "TM_EXTRA_SHOWS") || [];
const shows = [...live.shows, ...(Array.isArray(extra) ? extra : [])].filter((s) => s.slug && s.title);

const decode = (t) => String(t).replace(/<!\[CDATA\[([\s\S]*?)\]\]>/g, "$1").replace(/&#0?39;|&#x27;|&apos;/g, "'").replace(/&quot;/g, '"')
  .replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&#(\d+);/g, (_, n) => String.fromCharCode(+n)).trim();
const norm = (t) => decode(t).toLowerCase().replace(/[’'`!?.:,]/g, "").replace(/&/g, "and").replace(/[^a-z0-9]+/g, " ").trim();
const tag = (xml, name) => { const m = xml.match(new RegExp(`<${name}[^>]*>([\\s\\S]*?)</${name}>`)); return m ? decode(m[1]) : ""; };

// Headline patterns. Leaving is checked first ("final performance" beats "star").
const LEAVING = /\b(final performance|last performance|play(s|ing)? (his|her|their) (final|last)|depart|exits?\b|exiting|leav(e|es|ing)|farewell|bows? out|final bow)\b/i;
const JOINING = /\b(join(s|ing)?|will (play|star|lead|headline|return|step|take over|replace)|to (play|star|lead|headline|return|step|take over|replace)|takes? over|step(s|ping)? into|returns? to|returning to|replac(e|es|ing)|new cast|cast set|full cast|casting|cast (is )?announced|will be (played|led)|debut)\b/i;
const NOT_NYC = /\b(tour|touring|west end|london|chicago production|australia|toronto|la production|los angeles|old globe|regional|licens|concert|reading|workshop|benefit|film|movie|tv series|album|recording)\b/i;

// Match a headline to one of our shows. Long titles first so "Les Misérables" doesn't lose to "Les".
// Each show gets a few spellings: full title, the part before a colon ("Operation Mincemeat: A New
// Musical" → "Operation Mincemeat"), and without "Disney's" / a leading "The".
const variants = (t) => { const base = t.replace(/\(.*?\)/g, ""); const short = base.split(":")[0];
  return [...new Set([base, short, short.replace(/^disney'?s\s+/i, ""), short.replace(/^the\s+/i, "")].map(norm))].filter((k) => k.length >= 4); };
const titles = shows.flatMap((s) => variants(s.title).map((key) => ({ slug: s.slug, title: s.title, key })))
  .sort((a, b) => b.key.length - a.key.length);
const matchShow = (headline) => { const h = ` ${norm(headline)} `; const t = titles.find((t) => h.includes(` ${t.key} `)); return t || null; };

const seen = new Map((prev.items || []).map((i) => [i.link, i]));
let added = 0;
for (const feed of FEEDS) {
  try {
    const r = await fetch(feed.url, { headers: { "User-Agent": UA, Accept: "application/rss+xml, text/xml" } });
    if (!r.ok) throw new Error(`HTTP ${r.status}`);
    const xml = await r.text();
    for (const it of xml.split(/<item[\s>]/).slice(1)) {
      const title = tag(it, "title"), link = tag(it, "link"), date = tag(it, "pubDate");
      if (!title || !link || seen.has(link)) continue;
      if (NOT_NYC.test(title)) continue;
      const kind = LEAVING.test(title) ? "leaving" : JOINING.test(title) ? "joining" : null;
      if (!kind) continue;
      const show = matchShow(title);
      if (!show) continue;
      const d = date ? new Date(date) : new Date();
      seen.set(link, { title, link, source: feed.source, slug: show.slug, kind, date: d.toISOString().slice(0, 10) });
      added++;
      console.log(`+ ${show.slug} [${kind}] ${title}`);
    }
  } catch (e) { console.error(`${feed.source}: ${e.message}`); }
}
const cutoff = new Date(Date.now() - KEEP_DAYS * 864e5).toISOString().slice(0, 10);
const items = [...seen.values()].filter((i) => i.date >= cutoff).sort((a, b) => b.date.localeCompare(a.date));
writeFileSync(OUT, `// AUTO-GENERATED by scripts/update-castnews.mjs — do not edit by hand.
// Cast change headlines (headline, date, and link only) from Playbill's public news RSS feed, last ${KEEP_DAYS} days.
window.TM_CASTNEWS = ${JSON.stringify({ updatedAt: new Date().toISOString(), items }, null, 1)};
`);
console.log(`Done: ${added} new, ${items.length} kept`);
